// --- YAML writer -------------------------------------------------------------------------------

/** A YAML flow sequence (`["serve"]`), for Compose `command`/`test` arrays. */
class Flow {
  /** @param {readonly (string | number)[]} items */
  constructor(items) {
    this.items = items;
  }
}
/** A full-line comment inside a mapping or sequence. */
class Comment {
  /** @param {string} text */
  constructor(text) {
    this.text = text;
  }
}

const YAML_RESERVED = /^(?:true|false|yes|no|on|off|null|y|n|~)$/iu;
const YAML_PLAIN = /^[A-Za-z_/][A-Za-z0-9_./-]*$/u;

/** @param {string} s */
function yamlString(s) {
  return YAML_PLAIN.test(s) && !YAML_RESERVED.test(s) ? s : JSON.stringify(s);
}

/** @param {unknown} v */
function yamlScalar(v) {
  if (typeof v === "string") return yamlString(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (v instanceof Flow) return `[${v.items.map((i) => JSON.stringify(i)).join(", ")}]`;
  throw new Error(`not a YAML scalar: ${JSON.stringify(v)}`);
}

/** @param {unknown} v */
function isScalar(v) {
  return typeof v !== "object" || v === null || v instanceof Flow;
}

/**
 * Mappings are arrays of `[key, value]` pairs or Comment (insertion order is layout), sequences are
 * `{ seq: [...] }`. Keeping the two shapes distinct avoids guessing from a JS object.
 *
 * @param {Array<[string, unknown] | Comment>} map
 * @param {number} indent
 * @returns {string[]}
 */
function yamlMap(map, indent) {
  const pad = " ".repeat(indent);
  /** @type {string[]} */
  const lines = [];
  for (const item of map) {
    if (item instanceof Comment) {
      lines.push(`${pad}# ${item.text}`);
      continue;
    }
    const [key, value] = item;
    if (isScalar(value)) lines.push(`${pad}${key}: ${yamlScalar(value)}`);
    else if (Array.isArray(value) && value.length === 0) lines.push(`${pad}${key}: {}`);
    else if (!Array.isArray(value) && /** @type {{ seq: unknown[] }} */ (value).seq.length === 0)
      lines.push(`${pad}${key}: []`);
    else if (Array.isArray(value)) {
      lines.push(`${pad}${key}:`);
      lines.push(...yamlMap(value, indent + 2));
    } else {
      lines.push(`${pad}${key}:`);
      lines.push(...yamlSeq(/** @type {{ seq: unknown[] }} */ (value).seq, indent + 2));
    }
  }
  return lines;
}

/**
 * @param {unknown[]} seq
 * @param {number} indent
 * @returns {string[]}
 */
function yamlSeq(seq, indent) {
  const pad = " ".repeat(indent);
  /** @type {string[]} */
  const lines = [];
  for (const item of seq) {
    if (item instanceof Comment) lines.push(`${pad}# ${item.text}`);
    else if (isScalar(item)) lines.push(`${pad}- ${yamlScalar(item)}`);
    else if (Array.isArray(item)) {
      const inner = yamlMap(item, indent + 2);
      // First line of the mapping shares the dash.
      const first = inner.findIndex((l) => !l.trimStart().startsWith("#"));
      inner[first] = `${pad}- ${inner[first].slice(indent + 2)}`;
      lines.push(...inner);
    } else throw new Error("nested sequences are not used by these templates");
  }
  return lines;
}

/**
 * @param {string[]} headerLines
 * @param {Array<[string, unknown] | Comment>} doc
 */
function yamlDocument(headerLines, doc) {
  const out = [...headerLines.map((l) => (l === "" ? "#" : `# ${l}`)), ""];
  let first = true;
  for (const item of doc) {
    // A blank line between top-level keys.
    if (!first && !(item instanceof Comment)) out.push("");
    out.push(...yamlMap([item], 0));
    if (!(item instanceof Comment)) first = false;
  }
  return `${out.join("\n")}\n`;
}

// --- TOML writer (the subset fly.toml needs) ---------------------------------------------------

/** @param {unknown} v */
function tomlValue(v) {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(tomlValue).join(", ")}]`;
  throw new Error(`not a TOML value: ${JSON.stringify(v)}`);
}

/** @param {string} key */
function tomlKey(key) {
  return /^[A-Za-z0-9_-]+$/u.test(key) ? key : JSON.stringify(key);
}

/** @param {Array<[string, unknown] | Comment>} pairs */
function tomlPairs(pairs) {
  return pairs.map((p) =>
    p instanceof Comment ? `# ${p.text}`.trimEnd() : `${tomlKey(p[0])} = ${tomlValue(p[1])}`,
  );
}

// --- shared helpers ----------------------------------------------------------------------------

/** @param {string[]} args */
const fullCommand = (...args) => [...IMAGE_ENTRYPOINT, ...args].join(" ");

/** Markdown table cell text: a literal `|` would end the cell. */
/** @param {string} s */
const cell = (s) => s.replaceAll("|", "\\|");

/** @param {import("../deploy/platforms/source.mjs").EnvVar} e */
function describe(e) {
  return e.example ? `${e.description} e.g. ${e.example}` : e.description;
}

/** `openssl` command producing a value that satisfies the schema for a generated secret. */
/** @param {import("../deploy/platforms/source.mjs").EnvVar} e */
function opensslFor(e) {
  const bytes = e.bytes ?? 32;
  return e.name === "FUNDROOM_SECRET_KEY"
    ? `openssl rand -base64 ${bytes}`
    : `openssl rand -hex ${bytes}`;
}

/**
 * The same, as a Railway template function: hex keeps the value inside every schema's alphabet
 * (the key ring accepts hex of >= 64 characters; SESSION_SECRET needs >= 32 characters).
 *
 * @param {import("../deploy/platforms/source.mjs").EnvVar} e
 */
function railwaySecretFor(e) {
  return `\${{secret(${(e.bytes ?? 32) * 2}, "abcdef0123456789")}}`;
}

/**
 * The variable names a template sets for `e` (A-2 FIX `formerlySet` in the catalogue): the new
 * name, the old one, or both (same value).
 *
 * @param {import("../deploy/platforms/source.mjs").EnvVar} e
 * @returns {string[]}
 */
function templateNames(e) {
  if (!e.formerly || !e.formerlySet) return [e.name];
  return e.formerlySet === "old" ? [e.formerly] : [e.name, e.formerly];
}

/**
 * Upgrade note for variables renamed since a platform's template was first deployed (`formerly`
 * in the catalogue). The app reads the old name (with a doctor/boot warning), accepts both names
 * holding the same value and refuses to start when they differ. An image from before the rename
 * reads ONLY the old name and, without it, generates a new key, so every note says: upgrade the
 * image first, rename after, and keep both (same value) while an older image may still run.
 *
 * @param {"render" | "railway" | "fly" | "coolify"} platform
 * @returns {string[]}
 */
function renamedNote(platform) {
  const renamed = envFor(platform).filter((e) => e.formerly);
  if (renamed.length === 0) return [];
  const lines = renamed.map((e) => {
    const old = `\`${e.formerly}\``;
    const now = `\`${e.name}\``;
    // Railway and Fly secrets are set by hand, so the operator does the rename: say in what order.
    const order = `Upgrade the image first and rename after: an image from before the rename reads only ${old} and, without it, generates a new key (data written meanwhile is lost to the real key). Both names holding the same value are accepted (\`fundroom doctor\` warns); different values refuse to start, naming both by key fingerprint.`;
    const how = {
      render: `This Blueprint still generates the key under ${old} for one minor release: Render generates a separate random value per variable name and an env group cannot reference another variable, so a ${now} entry would be a second, different key. The app reads ${old} (\`fundroom doctor\` warns), so an existing install keeps its key when you sync. Do not add ${now} to the env group with any other value. A later release moves the Blueprint to ${now}; before syncing that one, add ${now} to the env group with ${old}'s value.`,
      railway: `An existing project keeps working on ${old} (\`fundroom doctor\` warns). ${order} Once every service runs the new image, create ${now} on the web service with the same value and point the worker's reference at it; delete ${old} only when you will not roll back to an older image.`,
      fly: `An existing app keeps working on ${old} (\`fundroom doctor\` warns). ${order} Once the new image is deployed, set ${now} to the same value (from your backup, or \`fly ssh console -C 'printenv ${e.formerly}'\`: Fly cannot show a secret) with \`fly secrets set\`; \`fly secrets unset ${e.formerly}\` only when you will not roll back to an older image.`,
      coolify: `For one minor release the stack sets both ${now} and ${old}, both fed by \`SERVICE_REALBASE64_SEEDHOSTKEY\` (one value), so an older image still finds its key. The magic name is kept on purpose: Coolify stores one generated value per name, so a new name would mint a new master key. Caddy mode: the domain variable is now \`FUNDROOM_DOMAIN\`; set it in Coolify before redeploying.`,
    }[platform];
    return `- ${now} was ${old}. ${how}`;
  });
  return ["", "**Upgrading from a pre-FundRoom template (renamed variables):**", "", ...lines];
}

// --- Render ------------------------------------------------------------------------------------

function renderBlueprint() {
  const p = PLATFORMS.render;
  const env = envFor("render");
  const shared = (/** @type {typeof env[number]} */ e) =>
    e.processes.includes("web") &&
    e.processes.includes("worker") &&
    (e.kind === "generate" ||
      (e.kind === "literal" && literalFor(e, "web") === literalFor(e, "worker")));

  /** @type {unknown[]} */
  const groupVars = [];
  for (const e of env.filter(shared)) {
    if (e.formerly && e.kind === "generate") {
      groupVars.push(
        new Comment(
          e.formerlySet === "old"
            ? `${e.formerly} is ${e.name}'s pre-rename name, kept here for one minor release: Render generates one value per name, so a ${e.name} entry would be a second, different key. The app reads ${e.formerly} (doctor warns). Never add ${e.name} with another value (deploy/render/README.md).`
            : `${e.name} was ${e.formerly}. Existing Blueprint: before syncing, add ${e.name} with ${e.formerly}'s value, or Render generates a new key next to the old one and the app refuses to start (deploy/render/README.md).`,
        ),
      );
    }
    for (const name of templateNames(e)) {
      groupVars.push(
        e.kind === "generate"
          ? [
              ["key", name],
              ["generateValue", true],
            ]
          : [
              ["key", name],
              ["value", literalFor(e, "web")],
            ],
      );
    }
  }

  /** @param {"web" | "worker"} proc */
  const serviceVars = (proc) => {
    /** @type {unknown[]} */
    const vars = [[["fromGroup", p.names.group]]];
    for (const e of env) {
      if (!e.processes.includes(proc) || shared(e)) continue;
      const fromWeb = proc === "worker" && e.processes.includes("web");
      switch (e.kind) {
        case "literal":
          vars.push([
            ["key", e.name],
            ["value", literalFor(e, proc)],
          ]);
          break;
        case "database":
          vars.push([
            ["key", e.name],
            [
              "fromDatabase",
              [
                ["name", p.names.database],
                ["property", "connectionString"],
              ],
            ],
          ]);
          break;
        case "generate":
        case "prompt":
        case "baseUrl":
          if (fromWeb) {
            vars.push([
              ["key", e.name],
              [
                "fromService",
                [
                  ["type", "web"],
                  ["name", p.names.web],
                  ["envVarKey", e.name],
                ],
              ],
            ]);
          } else if (e.kind === "generate") {
            vars.push([
              ["key", e.name],
              ["generateValue", true],
            ]);
          } else {
            vars.push(new Comment(`${e.name}: ${describe(e)}`));
            vars.push([
              ["key", e.name],
              ["sync", false],
            ]);
          }
          break;
      }
    }
    return vars;
  };

  const image = [["url", IMAGE]];
  return yamlDocument(
    [
      ...HEADER,
      "",
      "Render Blueprint: https://render.com/docs/blueprint-spec (deploy/render/README.md).",
      "Image-backed services: the ENTRYPOINT is the FundRoom CLI and CMD is `serve`, so neither",
      "service sets dockerCommand. Render's pre-deploy command replaces the ENTRYPOINT, which is",
      "why it spells out the whole node invocation. Pre-deploy needs a paid instance type.",
    ],
    [
      [
        "envVarGroups",
        {
          seq: [
            [
              ["name", p.names.group],
              ["envVars", { seq: groupVars }],
            ],
          ],
        },
      ],
      [
        "databases",
        {
          seq: [
            [
              ["name", p.names.database],
              ["plan", p.plans.database],
              ["databaseName", p.databaseName],
              ["user", p.databaseUser],
              ["postgresMajorVersion", p.postgresMajorVersion],
              // Private network only; add CIDRs here to reach it from outside Render.
              ["ipAllowList", { seq: [] }],
            ],
          ],
        },
      ],
      [
        "services",
        {
          seq: [
            [
              ["type", "web"],
              ["name", p.names.web],
              ["runtime", "image"],
              ["image", image],
              ["plan", p.plans.web],
              ["preDeployCommand", fullCommand("migrate")],
              ["healthCheckPath", READINESS_PATH],
              ["envVars", { seq: serviceVars("web") }],
            ],
            [
              ["type", "worker"],
              ["name", p.names.worker],
              ["runtime", "image"],
              ["image", image],
              ["plan", p.plans.worker],
              ["envVars", { seq: serviceVars("worker") }],
            ],
          ],
        },
      ],
    ],
  );
}

function renderReadmeBlock() {
  const p = PLATFORMS.render;
  const rows = envFor("render").map((e) => {
    const how = {
      literal: () => `\`${[...new Set(e.processes.map((x) => literalFor(e, x)))].join("` / `")}\``,
      generate: () => "generated by Render (`generateValue`)",
      prompt: () => "you enter it (`sync: false`)",
      baseUrl: () =>
        "you enter it (`sync: false`): `https://<service>.onrender.com` or your domain",
      database: () => `\`fromDatabase\` ${p.names.database}`,
    }[e.kind]();
    const names = templateNames(e)
      .map((n) => `\`${n}\``)
      .join(", ");
    return `| ${names} | ${e.processes.join(", ")} | ${how} | ${cell(e.description)} |`;
  });
  return [
    "| Variable | Process | Value | Notes |",
    "|---|---|---|---|",
    ...rows,
    "",
    `The worker reads every value you enter from the web service (\`fromService\` … \`envVarKey\`), so each one is typed once. Pre-deploy command: \`${fullCommand("migrate")}\`.`,
    ...renamedNote("render"),
  ].join("\n");
}

// --- Railway -----------------------------------------------------------------------------------

function railwayReadmeBlock() {
  const p = PLATFORMS.railway;
  const env = envFor("railway");
  /** @param {"web" | "worker"} proc */
  const table = (proc) => {
    const rows = env
      .filter((e) => e.processes.includes(proc))
      .map((e) => {
        let value;
        if (e.kind === "literal") value = `\`${literalFor(e, proc)}\``;
        else if (e.kind === "database") value = `\`\${{${p.names.database}.DATABASE_URL}}\``;
        else if (proc === "worker" && e.processes.includes("web"))
          value = `\`\${{${p.names.web}.${e.name}}}\``;
        else if (e.kind === "generate") value = `\`${railwaySecretFor(e)}\``;
        else if (e.kind === "baseUrl") value = "`https://${{RAILWAY_PUBLIC_DOMAIN}}`";
        else value = `*(template user enters it)*${e.example ? ` e.g. \`${e.example}\`` : ""}`;
        return `| \`${e.name}\` | ${value} | ${cell(e.description)} |`;
      });
    return ["| Variable | Value in the template | Notes |", "|---|---|---|", ...rows].join("\n");
  };
  return [
    `**Service \`${p.names.web}\`** — source image \`${IMAGE}\`; Settings → Deploy → Pre-deploy command \`${fullCommand("migrate")}\`; healthcheck path \`${READINESS_PATH}\`; Networking → generate a domain on port ${PORT}; no start command (the image's ENTRYPOINT + CMD run \`serve\`).`,
    "",
    table("web"),
    "",
    `**Service \`${p.names.worker}\`** — same image; no pre-deploy command, no healthcheck, no public domain.`,
    "",
    table("worker"),
    "",
    `**Service \`${p.names.database}\`** — Railway's PostgreSQL template (provides \`DATABASE_URL\` on the private network).`,
    ...renamedNote("railway"),
  ].join("\n");
}

// --- Fly.io ------------------------------------------------------------------------------------

function flyToml() {
  const p = PLATFORMS.fly;
  const env = envFor("fly");
  const literals = env.filter((e) => e.kind === "literal");
  const secrets = env.filter((e) => e.kind !== "literal");
  for (const e of literals) {
    if (literalFor(e, "web") !== literalFor(e, "worker") && e.processes.length > 1)
      throw new Error(`fly [env] is app-wide; ${e.name} differs per process`);
  }

  const lines = [
    ...HEADER.map((l) => `# ${l}`),
    "#",
    "# Fly Launch: https://fly.io/docs/reference/configuration/ (deploy/fly/README.md).",
    "# [processes] and release_command replace the image's CMD and keep its ENTRYPOINT (the",
    "# FundRoom CLI). [env] is app-wide, so each process group gets its roles on the command line.",
    "#",
    "# Set with `fly secrets set` (deploy/fly/README.md), never in this file:",
    ...secrets.flatMap((e) => [
      `# secret: ${e.name} — ${
        e.kind === "database"
          ? "set by `fly mpg attach`"
          : e.kind === "generate"
            ? `\`${opensslFor(e)}\``
            : describe(e)
      }`,
      ...(e.formerly
        ? [
            `#   (was ${e.formerly}: an existing app keeps working on the old name. Upgrade the image`,
            "#   first, then set the new name to the SAME value; an older image reads only the old",
            "#   name and would generate a new key. Different values refuse to start; see",
            "#   deploy/fly/README.md)",
          ]
        : []),
    ]),
    "",
    ...tomlPairs([
      ["app", p.app],
      ["kill_signal", "SIGTERM"],
      ["kill_timeout", p.killTimeout],
    ]),
    "",
    "[build]",
    ...tomlPairs([["image", IMAGE]]),
    "",
    "[deploy]",
    ...tomlPairs([
      ["release_command", "migrate"],
      ["strategy", "rolling"],
    ]),
    "",
    "[env]",
    ...tomlPairs(literals.map((e) => [e.name, /** @type {string} */ (literalFor(e, "web"))])),
    "",
    "[processes]",
    ...tomlPairs([
      [p.groups.web, "serve --roles api,web"],
      [p.groups.worker, "serve --roles worker"],
    ]),
    "",
    "[http_service]",
    ...tomlPairs([
      ["internal_port", PORT],
      ["force_https", true],
      ["auto_stop_machines", "off"],
      ["auto_start_machines", true],
      ["min_machines_running", 1],
      ["processes", [p.groups.web]],
    ]),
    "",
    "[[http_service.checks]]",
    ...tomlPairs([
      ["grace_period", "30s"],
      ["interval", "15s"],
      ["method", "GET"],
      ["path", READINESS_PATH],
      ["timeout", "5s"],
    ]),
    "",
    "[[vm]]",
    ...tomlPairs([
      ["size", p.vm.web.size],
      ["memory", p.vm.web.memory],
      ["processes", [p.groups.web]],
    ]),
    "",
    "[[vm]]",
    ...tomlPairs([
      ["size", p.vm.worker.size],
      ["memory", p.vm.worker.memory],
      ["processes", [p.groups.worker]],
    ]),
  ];
  return `${lines.join("\n")}\n`;
}

function flyReadmeBlock() {
  const env = envFor("fly");
  const secrets = env.filter(
    (e) => e.kind === "generate" || e.kind === "prompt" || e.kind === "baseUrl",
  );
  const assign = secrets.map((e) => {
    if (e.kind === "generate") return `  ${e.name}="$(${opensslFor(e)})"`;
    if (e.kind === "baseUrl") return `  ${e.name}="https://<app>.fly.dev"`;
    return `  ${e.name}="${e.example ?? `<${e.name.toLowerCase()}>`}"`;
  });
  const literals = env.filter((e) => e.kind === "literal");
  return [
    "```sh",
    "fly secrets set --stage \\",
    `${assign.join(" \\\n")}`,
    "```",
    "",
    "Set in `fly.toml` `[env]` (not secret): " +
      literals.map((e) => `\`${e.name}=${literalFor(e, "web")}\``).join(", ") +
      ".",
    "",
    "`DATABASE_URL` comes from `fly mpg attach`.",
    ...renamedNote("fly"),
  ].join("\n");
}

// --- Coolify -----------------------------------------------------------------------------------

/**
 * Coolify's generated values (https://coolify.io/docs/knowledge-base/docker/compose): declared
 * by using them, generated once per stack, shared by every service in it.
 *
 * @param {import("../deploy/platforms/source.mjs").EnvVar} e
 * @param {"traefik" | "caddy"} mode
 */
function coolifyValue(e, mode) {
  switch (e.kind) {
    case "literal":
      return literalFor(e, "web");
    case "database":
      return "postgres://seedhost:${SERVICE_PASSWORD_POSTGRES}@db:5432/seedhost";
    case "baseUrl":
      // Not ${SERVICE_URL_APP}: without an https wildcard domain on the server Coolify fills it
      // with an http sslip.io URL, which APP_ENV=prod rejects (migrate exits 2, app never starts),
      // and it does not reliably follow a domain edited in the UI (coollabsio/coolify#6124).
      return mode === "traefik" ? "${BASE_URL:?}" : "https://${FUNDROOM_DOMAIN:?}";
    case "generate":
      return {
        // The magic name keeps its pre-rename spelling on purpose: Coolify generates and stores
        // one value per name, so a new name would mint a NEW master key for an existing stack.
        FUNDROOM_SECRET_KEY: "${SERVICE_REALBASE64_SEEDHOSTKEY}",
        SESSION_SECRET: "${SERVICE_PASSWORD_64_SESSION}",
        SETUP_TOKEN: "${SERVICE_HEX_32_SETUP}",
        METRICS_TOKEN: "${SERVICE_PASSWORD_METRICS}",
      }[e.name];
    case "prompt":
      return e.required ? `\${${e.name}:?}` : `\${${e.name}:-}`;
  }
  throw new Error(`no Coolify value for ${e.name}`);
}

/** @param {"traefik" | "caddy"} mode */
function coolifyCompose(mode) {
  const id = mode === "traefik" ? "coolify" : "coolify-caddy";
  const env = envFor(id);
  for (const e of env) {
    if (coolifyValue(e, mode) === undefined) throw new Error(`no Coolify value for ${e.name}`);
  }
  // `migrate` gets the app's environment, exactly as the PaaS pre-deploy steps do: it loads the
  // same config (MAIL_FROM, SMTP_URL, …) and would refuse to start without it.
  /** @param {"app" | "migrate"} service */
  const appEnv = (service) => {
    const list = env.flatMap((e) => templateNames(e).map((n) => `${n}=${coolifyValue(e, mode)}`));
    // Declaring SERVICE_URL_APP_3000 on `app` is what makes Coolify give that service a domain
    // and route it to port 3000; `migrate` only reads the resulting SERVICE_URL_APP.
    return mode === "traefik" && service === "app" ? [`SERVICE_URL_APP_${PORT}`, ...list] : list;
  };
  const hardening = [
    ["read_only", true],
    ["tmpfs", { seq: ["/tmp:size=256m"] }],
    ["volumes", { seq: ["data:/data"] }],
    ["security_opt", { seq: ["no-new-privileges:true"] }],
    ["cap_drop", { seq: ["ALL"] }],
  ];
  /** @type {Array<[string, unknown]>} */
  const services = [
    [
      "db",
      [
        ["image", "postgres:18-alpine"],
        ["restart", "unless-stopped"],
        [
          "environment",
          {
            seq: [
              "POSTGRES_USER=seedhost",
              "POSTGRES_PASSWORD=${SERVICE_PASSWORD_POSTGRES}",
              "POSTGRES_DB=seedhost",
              "POSTGRES_INITDB_ARGS=--data-checksums",
            ],
          },
        ],
        ["volumes", { seq: ["pgdata:/var/lib/postgresql"] }],
        [
          "healthcheck",
          [
            ["test", new Flow(["CMD-SHELL", "pg_isready -U seedhost -d seedhost"])],
            ["interval", "5s"],
            ["timeout", "3s"],
            ["retries", 20],
          ],
        ],
        ["security_opt", { seq: ["no-new-privileges:true"] }],
      ],
    ],
    [
      "migrate",
      [
        ["image", IMAGE],
        ["restart", "no"],
        ["command", new Flow(["migrate"])],
        // A one-shot: it exits 0, which must not mark the stack unhealthy in Coolify.
        ["exclude_from_hc", true],
        ["environment", { seq: appEnv("migrate") }],
        ...hardening,
        ["depends_on", [["db", [["condition", "service_healthy"]]]]],
      ],
    ],
    [
      "app",
      [
        ["image", IMAGE],
        ["restart", "unless-stopped"],
        ["command", new Flow(["serve"])],
        ["environment", { seq: appEnv("app") }],
        ...hardening,
        [
          "depends_on",
          [
            ["db", [["condition", "service_healthy"]]],
            ["migrate", [["condition", "service_completed_successfully"]]],
          ],
        ],
        ["expose", { seq: [String(PORT)] }],
        [
          "healthcheck",
          [
            // Liveness, as in deploy/compose/compose.yaml: a Postgres blip must not restart it.
            ["test", new Flow(["CMD", "/nodejs/bin/node", "/app/healthcheck.js"])],
            ["interval", "15s"],
            ["timeout", "5s"],
            ["start_period", "40s"],
            ["retries", 3],
          ],
        ],
      ],
    ],
  ];
  if (mode === "caddy") {
    services.push([
      "caddy",
      [
        ["image", "caddy:2-alpine"],
        ["restart", "unless-stopped"],
        ["ports", { seq: ["80:80", "443:443", "443:443/udp"] }],
        [
          "environment",
          { seq: ["FUNDROOM_DOMAIN=${FUNDROOM_DOMAIN:?}", "ACME_EMAIL=${ACME_EMAIL:-}"] },
        ],
        [
          "volumes",
          {
            seq: [
              // Repository-relative: deploy this stack from the Git repository (README).
              "../caddy/Caddyfile:/etc/caddy/Caddyfile:ro",
              "caddy_data:/data",
              "caddy_config:/config",
            ],
          },
        ],
        ["depends_on", [["app", [["condition", "service_healthy"]]]]],
        ["security_opt", { seq: ["no-new-privileges:true"] }],
      ],
    ]);
  }
  const volumes = ["pgdata", "data", ...(mode === "caddy" ? ["caddy_data", "caddy_config"] : [])];
  const intro =
    mode === "traefik"
      ? [
          "Coolify stack behind Coolify's own proxy (Traefik), which routes the app's domain",
          `(SERVICE_URL_APP_${PORT}) and issues its certificate. BEFORE THE FIRST DEPLOY: give the app`,
          "an https:// domain in Coolify and set BASE_URL to exactly that URL — APP_ENV=prod refuses",
          "an http BASE_URL, so an http sslip.io default never starts. Custom domains:",
          "CUSTOM_DOMAIN_DRIVER=manual — add each verified customer domain to the app in Coolify.",
        ]
      : [
          "Coolify stack that keeps Caddy as the edge for on-demand TLS on customer domains",
          "(CUSTOM_DOMAIN_DRIVER=caddy-ask). Caddy binds 80/443, so Coolify's proxy must be stopped",
          "on this server, and the stack must be deployed from the Git repository so that",
          "../caddy/Caddyfile resolves (deploy/coolify/README.md).",
        ];
  return yamlDocument(
    [
      ...HEADER,
      "",
      ...intro,
      "One all-in-one process (embedded worker) and a volume: STORAGE_DRIVER=fs.",
    ],
    [
      ["services", services],
      ["volumes", volumes.map((v) => [v, []])],
    ],
  );
}

function coolifyReadmeBlock() {
  const t = envFor("coolify");
  const c = envFor("coolify-caddy");
  const names = [...new Set([...t, ...c].map((e) => e.name))];
  const rows = names.map((name) => {
    const et = t.find((e) => e.name === name);
    const ec = c.find((e) => e.name === name);
    const v = (/** @type {typeof et} */ e, /** @type {"traefik" | "caddy"} */ m) =>
      e ? `\`${coolifyValue(e, m)}\`` : "—";
    const label = templateNames(/** @type {NonNullable<typeof et>} */ (et ?? ec))
      .map((n) => `\`${n}\``)
      .join(", ");
    return `| ${label} | ${v(et, "traefik")} | ${v(ec, "caddy")} |`;
  });
  return [
    "| Variable | `compose.coolify.yaml` (Traefik) | `compose.coolify-caddy.yaml` (Caddy) |",
    "|---|---|---|",
    ...rows,
    "",
    "A `:?` value is one Coolify refuses to deploy without; the `SERVICE_…` values are generated by Coolify once per stack.",
    ...renamedNote("coolify"),
  ].join("\n");
}

