/**
 * @param {string} readme current README text
 * @param {string} block generated markdown
 */
export function replaceBlock(readme, block) {
  const start = readme.indexOf(BEGIN_MARK);
  const end = readme.indexOf(END_MARK);
  if (start < 0 || end < start) throw new Error("README is missing the generated-block markers");
  return `${readme.slice(0, start + BEGIN_MARK.length)}\n${block}\n${readme.slice(end)}`;
}

/** @returns {Map<string, string>} repo-relative path → full expected content */
export function renderAll() {
  /** @type {Map<string, string>} */
  const files = new Map();
  files.set("deploy/render/render.yaml", renderBlueprint());
  files.set("deploy/fly/fly.toml", flyToml());
  files.set("deploy/coolify/compose.coolify.yaml", coolifyCompose("traefik"));
  files.set("deploy/coolify/compose.coolify-caddy.yaml", coolifyCompose("caddy"));
  /** @type {Array<[string, string]>} */
  const blocks = [
    ["deploy/render/README.md", renderReadmeBlock()],
    ["deploy/railway/README.md", railwayReadmeBlock()],
    ["deploy/fly/README.md", flyReadmeBlock()],
    ["deploy/coolify/README.md", coolifyReadmeBlock()],
  ];
  for (const [path, block] of blocks) {
    files.set(path, replaceBlock(readFileSync(join(ROOT, path), "utf8"), block));
  }
  return files;
}

/** @returns {string[]} repo-relative paths whose committed content differs */
export function staleFiles() {
  const stale = [];
  for (const [path, content] of renderAll()) {
    let current = "";
    try {
      current = readFileSync(join(ROOT, path), "utf8");
    } catch {
      /* missing → stale */
    }
    if (current !== content) stale.push(path);
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles();
    if (stale.length > 0) {
      console.error(
        `deploy templates are stale (${stale.join(", ")}): run pnpm gen:deploy and commit the result.`,
      );
      process.exit(1);
    }
  } else {
    for (const [path, content] of renderAll()) writeFileSync(join(ROOT, path), content);
    process.stdout.write(`wrote ${[...renderAll().keys()].join(", ")}\n`);
  }
}
