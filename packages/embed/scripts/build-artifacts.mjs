#!/usr/bin/env node
/*
 * Bundles the loader and compiles the result into `src/generated/artifacts.ts`.
 *
 * Why a generated TypeScript module and not two files in `dist/` that the server reads at
 * runtime: the distroless image ships `dist/` and nothing else, the server may be started from
 * anywhere, and "find the package root at runtime" is a Docker-layout assumption that breaks
 * quietly on the day somebody changes the build. The same reasoning, and the same
 * committed-generated-file pattern, as `packages/compliance/scripts/build-templates.mjs`:
 * the artefact is in git so a reviewer can diff it, and a unit test rebuilds it in memory and
 * fails if the two have drifted.
 *
 * The gzip budget (spec §4, plan §16) is enforced *here*, not in a dashboard. A loader that
 * quietly grew to 40 KB is a loader that made every customer's marketing page slower, and the
 * only moment anybody will notice is the moment the build refuses.
 *
 *   node scripts/build-artifacts.mjs           # write dist/ and src/generated/artifacts.ts
 *   node scripts/build-artifacts.mjs --check   # fail if the committed file is stale (CI)
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = join(here, "..");
export const ENTRY = join(PACKAGE_DIR, "src", "index.ts");
export const OUTPUT_FILE = join(PACKAGE_DIR, "src", "generated", "artifacts.ts");

/** design/08 §5 "Bundle size": ≤ 5 KB gzip for the loader. Over budget fails the build. */
export const GZIP_BUDGET_BYTES = 5 * 1024;

const JS_CONTENT_TYPE = "text/javascript; charset=utf-8";
const JSON_CONTENT_TYPE = "application/json; charset=utf-8";

/**
 * ES2020 is the floor, and it is not arbitrary: the embed's session cookie needs CHIPS, which
 * arrived in Chrome 115 / Safari 18.4, so every browser that can hold a session here is years
 * past ES2020. Aiming lower would only add transpilation weight nobody can use.
 */
const TARGET = ["es2020"];

function version() {
  return JSON.parse(readFileSync(join(PACKAGE_DIR, "package.json"), "utf8")).version;
}

/** `sha384-<base64>`, exactly as an `integrity` attribute wants it. */
export function integrityOf(bytes) {
  return `sha384-${createHash("sha384").update(bytes).digest("base64")}`;
}

async function bundle(format, globalName) {
  const result = await build({
    entryPoints: [ENTRY],
    outfile: join(PACKAGE_DIR, "dist", format === "iife" ? "embed.js" : "embed.mjs"),
    bundle: true,
    minify: true,
    format,
    target: TARGET,
    platform: "browser",
    charset: "utf8",
    legalComments: "none",
    write: false,
    ...(globalName === undefined ? {} : { globalName }),
    // One banner line so a person who opens the served file knows what they are looking at and
    // which version to report. `legalComments: "none"` strips everything else.
    banner: { js: `/*! @fundroom/embed ${version()} | MIT */` },
  });
  const file = result.outputFiles[0];
  if (file === undefined) throw new Error(`esbuild produced no output for ${format}`);
  return { bytes: Buffer.from(file.contents), text: file.text };
}

/**
 * Builds both formats plus the SRI manifest, in a stable order. No timestamps anywhere: the
 * output has to be byte-identical across runs or the drift check is noise.
 */
export async function buildArtifacts() {
  const v = version();
  const iife = await bundle("iife", "SeedHost");
  const esm = await bundle("esm", undefined);

  const files = [
    { path: "embed.js", contentType: JS_CONTENT_TYPE, ...iife },
    { path: "embed.mjs", contentType: JS_CONTENT_TYPE, ...esm },
  ];

  const manifest = {
    version: v,
    artifacts: Object.fromEntries(
      files.map((f) => [
        f.path,
        { contentType: f.contentType, integrity: integrityOf(f.bytes), bytes: f.bytes.length },
      ]),
    ),
  };
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  files.push({
    path: "manifest.json",
    contentType: JSON_CONTENT_TYPE,
    bytes: Buffer.from(manifestText, "utf8"),
    text: manifestText,
  });

  return {
    version: v,
    gzipBytes: gzipSync(iife.bytes, { level: 9 }).length,
    esmGzipBytes: gzipSync(esm.bytes, { level: 9 }).length,
    artifacts: files.map((f) => ({
      path: f.path,
      contentType: f.contentType,
      code: f.text,
      sha384: integrityOf(f.bytes),
      version: v,
      rawBytes: f.bytes.length,
    })),
  };
}

const HEADER = `// GENERATED by scripts/build-artifacts.mjs from src/ — do not edit by hand.
// Run \`pnpm --filter @fundroom/embed codegen\`; \`artifacts.test.ts\` fails the build if this
// file and the loader source have drifted, and \`codegen:check\` is the same gate in CI.
`;

/** The TypeScript source of the generated module, so the drift test can build it in memory. */
export async function buildArtifactsModule() {
  const built = await buildArtifacts();
  const entries = built.artifacts
    .map(
      (a) => `  {
    path: ${JSON.stringify(a.path)},
    contentType: ${JSON.stringify(a.contentType)},
    sha384: ${JSON.stringify(a.sha384)},
    version: ${JSON.stringify(a.version)},
    code: ${JSON.stringify(a.code)},
  },`,
    )
    .join("\n");

  return {
    built,
    source: `${HEADER}
import type { EmbedArtifact } from "../artifact-types.js";

/** The version these bytes were built from; the pinned URL segment. */
export const EMBED_VERSION = ${JSON.stringify(built.version)};

export const EMBED_ARTIFACTS: readonly EmbedArtifact[] = Object.freeze([
${entries}
]);
`,
  };
}

function report(built) {
  const budget = `${GZIP_BUDGET_BYTES} B`;
  const lines = [
    `embed: embed.js  ${built.artifacts[0].rawBytes} B raw, ${built.gzipBytes} B gzip (budget ${budget})`,
    `embed: embed.mjs ${built.artifacts[1].rawBytes} B raw, ${built.esmGzipBytes} B gzip`,
  ];
  process.stdout.write(`${lines.join("\n")}\n`);
}

async function main() {
  const check = process.argv.includes("--check");
  const { built, source } = await buildArtifactsModule();
  report(built);

  if (built.gzipBytes > GZIP_BUDGET_BYTES) {
    process.stderr.write(
      `embed: FAIL — embed.js is ${built.gzipBytes} B gzip, over the ${GZIP_BUDGET_BYTES} B ` +
        "budget. Take something out of the loader.\n",
    );
    process.exit(1);
  }

  if (check) {
    const current = readFileSync(OUTPUT_FILE, "utf8");
    if (current !== source) {
      process.stderr.write(
        "embed: FAIL — src/generated/artifacts.ts is stale. Run " +
          "`pnpm --filter @fundroom/embed codegen` and commit the result.\n",
      );
      process.exit(1);
    }
    process.stdout.write("embed: generated artifacts are current\n");
    return;
  }

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, source, "utf8");
  const dist = join(PACKAGE_DIR, "dist");
  mkdirSync(dist, { recursive: true });
  for (const artifact of built.artifacts) {
    writeFileSync(join(dist, artifact.path), artifact.code, "utf8");
  }
  process.stdout.write(`embed: wrote ${OUTPUT_FILE} and dist/{embed.js,embed.mjs,manifest.json}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
